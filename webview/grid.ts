function isTypingTarget(t: EventTarget | null): boolean {
  if (t === editor) return !!S.editing;
  return t instanceof HTMLInputElement || t instanceof HTMLTextAreaElement || t instanceof HTMLSelectElement;
}

document.addEventListener('keydown', (e) => {
  const mod = e.metaKey || e.ctrlKey;
  if (mod && e.key.toLowerCase() === 's') {
    e.preventDefault();
    const active = document.activeElement;
    if (active instanceof HTMLElement && active !== editor) active.blur(); // commit a pending form field first
    save();
    return;
  }
  if (!$('modal').hidden) {
    if (e.key === 'Escape') closeModal();
    return;
  }
  if (e.key === 'Escape') {
    $('menu').hidden = true;
    hideBanner();
  }
  if (mod && e.key.toLowerCase() === 'f') {
    e.preventDefault();
    $<HTMLInputElement>('search')?.focus();
    return;
  }
  if (isTypingTarget(e.target) || S.editing) return;

  const key = e.key;
  if (mod && key.toLowerCase() === 'z') return e.preventDefault(), undo();
  if (mod && key.toLowerCase() === 'a') {
    e.preventDefault();
    if (!S.rows.length) return;
    S.anchor = { r: 0, c: 0 };
    S.focus = { r: S.rows.length - 1, c: S.columns.length - 1 };
    paintSelection();
    return renderStatusLight();
  }
  if ((mod && key.toLowerCase() === 'r') || key === 'F5') return e.preventDefault(), S.mode === 'table' && load(S.offset);
  if (mod && (key === 'Backspace' || key === 'Delete')) return e.preventDefault(), deleteSelectedRows();
  if (!S.focus) return;

  const page = Math.max(1, Math.floor(scroller.clientHeight / 26) - 1);
  switch (key) {
    case 'ArrowUp':
      return e.preventDefault(), mod ? select({ r: 0, c: S.focus.c }, e.shiftKey) : move(-1, 0, e.shiftKey);
    case 'ArrowDown':
      return e.preventDefault(), mod ? select({ r: S.rows.length - 1, c: S.focus.c }, e.shiftKey) : move(1, 0, e.shiftKey);
    case 'ArrowLeft':
      return e.preventDefault(), mod ? select({ r: S.focus.r, c: 0 }, e.shiftKey) : move(0, -1, e.shiftKey);
    case 'ArrowRight':
      return e.preventDefault(), mod ? select({ r: S.focus.r, c: S.columns.length - 1 }, e.shiftKey) : move(0, 1, e.shiftKey);
    case 'PageDown':
      return e.preventDefault(), move(page, 0, e.shiftKey);
    case 'PageUp':
      return e.preventDefault(), move(-page, 0, e.shiftKey);
    case 'Tab':
      return e.preventDefault(), move(0, e.shiftKey ? -1 : 1);
    case 'Enter':
    case 'F2':
      return e.preventDefault(), startEdit();
    case 'Delete':
    case 'Backspace':
      return e.preventDefault(), S.mode === 'table' && setNullSelected();
    case 'ContextMenu': {
      const box = cellEl(S.focus)?.getBoundingClientRect();
      if (box) cellMenu(box.left + 8, box.bottom);
      return e.preventDefault();
    }
  }
  // Plain characters are not blocked: they land in the hidden textarea and `input` opens the editor.
  if (!mod && !e.altKey && key.length === 1 && e.target !== editor) placeEditor();
});

