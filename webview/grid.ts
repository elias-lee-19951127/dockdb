type Category = 'text' | 'number' | 'bool' | 'date' | 'json' | 'id' | 'binary' | 'other';

const CATEGORY: Record<Category, { badge: string; label: string; help: string }> = {
  text: { badge: 'abc', label: 'Text', help: 'Any text.' },
  number: { badge: '123', label: 'Number', help: 'Digits only, e.g. 42 or 3.14.' },
  bool: { badge: 'y/n', label: 'Yes / No', help: 'true or false.' },
  date: { badge: 'date', label: 'Date / time', help: 'e.g. 2026-09-22 or 2026-09-22 10:30:00.' },
  json: { badge: '{ }', label: 'JSON / nested data', help: 'Structured data such as {"key": "value"} or [1, 2].' },
  id: { badge: 'id', label: 'Identifier', help: 'A unique ID generated by the database.' },
  binary: { badge: '01', label: 'Binary', help: 'Raw bytes (files, images…). Shown as hex.' },
  other: { badge: '?', label: 'Other', help: 'A special database type.' },
};

function category(col: GridColumn): Category {
  const t = (col.dataType ?? '').toLowerCase();
  if (!t) return 'other';
  if (t === 'objectid' || t === 'uniqueidentifier' || t.includes('uuid')) return 'id';
  if (/bool|^bit(\(1\))?$|^tinyint\(1\)$/.test(t)) return 'bool';
  if (/interval|point/.test(t)) return 'other';
  if (/int|serial|numeric|decimal|real|double|float|money|number|^long$/.test(t)) return 'number';
  if (/date|time|year/.test(t)) return 'date';
  if (/json|^object$|^array$|\[\]$/.test(t)) return 'json';
  if (/char|text|string|clob|enum|set\(|citext|^name$/.test(t)) return 'text';
  if (/blob|bytea|binary/.test(t)) return 'binary';
  return 'other';
}

/** Postgres returns t/f, MySQL/SQLite 1/0 — show true/false for everyone. */
const boolLabel = (v: string) => (/^(t|true|1)$/i.test(v) ? 'true' : /^(f|false|0)$/i.test(v) ? 'false' : v);

/** Must be filled in when adding a row: NOT NULL without a default. */
const isRequired = (col: GridColumn) => col.nullable === false && !col.hasDefault && !col.isAutoIncrement;
const refName = (col: GridColumn) => (col.references ? col.references.table.name : '');

function columnTooltip(col: GridColumn): string {
  const cat = CATEGORY[category(col)];
  const lines = [col.name, `Type: ${col.dataType ?? 'unknown'} — ${cat.label}. ${cat.help}`];
  if (isRequired(col)) lines.push('Required: must have a value when you add a row.');
  else if (col.nullable === false) lines.push('Cannot be empty (the database fills in a default).');
  else if (col.nullable) lines.push('Optional: may be empty (NULL).');
  if (col.isPrimaryKey) lines.push('Primary key: uniquely identifies each row.');
  if (col.isAutoIncrement) lines.push('Filled in automatically when you add a row.');
  if (col.references) lines.push(`Points to ${col.references.table.name}.${col.references.column} — click ↗ in a cell to open that row.`);
  lines.push('', 'Click: sort · Right-click or ▾: more options');
  return lines.join('\n');
}

