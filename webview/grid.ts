function posFromEvent(e: MouseEvent): Pos | null {
  const td = (e.target as HTMLElement).closest('td');
  const tr = td?.parentElement as HTMLTableRowElement | undefined;
  if (!td || !tr || tr.parentElement !== tbody) return null;
  const r = Number(tr.dataset.r);
  if (td.classList.contains('rownum')) return { r, c: -1 };
  return { r, c: td.cellIndex - 1 };
}

