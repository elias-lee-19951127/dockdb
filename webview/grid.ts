function sortClientSide() {
  const it = S.results[S.activeResult];
  if (!it) return;
  const rows = it.rows.map((r) => ({ key: null, orig: r, cur: r, status: 'clean' as Status, touched: new Set<number>() }));
  if (S.sort) {
    const c = S.columns.findIndex((col) => col.name === S.sort!.column);
    const sign = S.sort.dir === 'asc' ? 1 : -1;
    const collator = new Intl.Collator(undefined, { numeric: true, sensitivity: 'base' });
    rows.sort((a, b) => {
      const x = a.cur[c];
      const y = b.cur[c];
      if (x === y) return 0;
      if (x === null) return 1;
      if (y === null) return -1;
      return collator.compare(x, y) * sign;
    });
  }
  S.rows = rows;
  renderGrid();
}

