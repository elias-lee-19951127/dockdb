// ───────────────────────── messages ─────────────────────────

window.addEventListener('message', (ev: MessageEvent<ToWebview>) => {
  const m = ev.data;
  switch (m.type) {
    case 'table-init':
      Object.assign(S, {
        mode: 'table',
        kind: m.kind,
        safety: m.safety,
        title: m.title,
        subtitle: m.subtitle,
        columns: m.columns,
        editable: m.editable,
        readOnlyReason: m.readOnlyReason,
        pageSize: m.pageSize,
        sort: m.sort,
        filter: m.filter,
        where: m.initialFilter ?? '',
        filterOpen: !!m.initialFilter,
        widths: [],
      });
      renderToolbar();
      load(0);
      break;
    case 'page':
      setLoading(false);
      S.offset = m.offset;
      S.hasMore = m.hasMore;
      S.durationMs = m.durationMs;
      if (m.columns) {
        // MongoDB: this page revealed new fields → add columns, keep existing widths.
        const old = new Map(S.columns.map((c, i) => [c.name, S.widths[i]]));
        const fresh = autoWidths(m.columns, m.rows);
        S.widths = m.columns.map((c, i) => old.get(c.name) ?? fresh[i]);
        S.columns = m.columns;
      }
      S.rows = m.rows.map((r, i) => ({ key: m.keys[i] ?? null, orig: r, cur: [...r], status: 'clean', touched: new Set() }));
      S.undo = [];
      S.invalid.clear();
      if (!S.widths.length) S.widths = autoWidths(S.columns, m.rows);
      clampSelection();
      renderGrid();
      break;
    case 'total':
      S.total = m.total;
      renderStatus();
      break;
    case 'running':
      S.mode = 'results';
      S.title = m.title;
      S.runningSql = m.sql;
      setLoading(true);
      renderToolbar();
      break;
    case 'results':
      S.mode = 'results';
      S.title = m.title;
      S.results = m.items;
      setLoading(false);
      showResult(Math.max(0, m.items.findIndex((it) => it.columns.length > 0 || it.error)));
      renderToolbar();
      break;
    case 'error':
      setLoading(false);
      showBanner(m.message, m.hint, m.detail);
      break;
    case 'saved':
      toast(`Saved — ${plural(m.affected, rowWord())} changed`);
      closeModal();
      load(S.offset, true);
      break;
    case 'sql-preview':
      showSqlPreview(m.title, m.sql);
      break;
    case 'apply-filter':
      S.where = m.where;
      S.filterOpen = true;
      load(0).then(renderToolbar);
      break;
  }
});

function setLoading(on: boolean) {
  S.loading = on;
  document.body.classList.toggle('loading', on);
}

async function load(offset: number, force = false) {
  if (!force && pendingCount() && !(await confirmModal('Discard your unsaved changes?', 'Discard changes', 'They have not been written to the database yet.'))) return;
  hideBanner();
  setLoading(true);
  S.total = undefined;
  post({ type: 'load', offset: Math.max(0, offset), where: S.where, search: S.search, sort: S.sort });
}

